function androidFiles(o: ExampleOptions, pkg: string): ExampleFile[] {
  const base = `${pkg}.clayver`;
  const setup = `${HEADER("//")}
package ${base}

import android.app.Application
import ${SDK.android.packageName}.Clayver
import ${SDK.android.packageName}.ClayverOptions
import com.google.firebase.auth.FirebaseAuth
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch

/**
 * Call [ClayverSetup.configure] from your Application.onCreate():
 *
 *     class MyApp : Application() {
 *         override fun onCreate() { super.onCreate(); ClayverSetup.configure(this) }
 *     }
 */
object ClayverSetup {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main)

    val options = ClayverOptions(projectId = "${o.workspace}", functionsRegion = "${o.region}")

    fun configure(app: Application) {
        scope.launch {
            runCatching { Clayver.configure(app, options) }
                .onFailure { android.util.Log.w("Clayver", "configure failed", it) }
        }
    }

    /**
     * Optional: call after your Firebase Auth sign-in. Clayver already follows the signed-in
     * user; properties are shown to agents next to the conversation.
     */
    suspend fun didSignIn() {
        Clayver.setUserProperties(mapOf("plan" to "pro"))
    }

    /**
     * Sign out through here: Clayver removes this device's push registrations while the
     * user is still signed in, then the user is signed out of Firebase Auth.
     */
    suspend fun signOut() {
        Clayver.logout()
        FirebaseAuth.getInstance().signOut()
    }
}
`;
  const messaging = `${HEADER("//")}
package ${base}

import ${SDK.android.packageName}.Clayver
import com.google.firebase.messaging.FirebaseMessagingService
import com.google.firebase.messaging.RemoteMessage
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch

/**
 * Forwards FCM tokens and Clayver pushes to the SDK. Register it in AndroidManifest.xml:
 *
 *     <service android:name=".clayver.ClayverMessagingService" android:exported="false">
 *         <intent-filter>
 *             <action android:name="com.google.firebase.MESSAGING_EVENT" />
 *         </intent-filter>
 *     </service>
 *
 * If your app already has a FirebaseMessagingService, call these two methods from it instead.
 */
class ClayverMessagingService : FirebaseMessagingService() {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    override fun onNewToken(token: String) {
        scope.launch { runCatching { Clayver.setPushToken(token) } }
    }

    override fun onMessageReceived(message: RemoteMessage) {
        if (Clayver.isClayverNotification(message.data)) {
            Clayver.handleNotification(this, message.data)
        }
    }
}
`;
  const button = `${HEADER("//")}
package ${base}

import android.Manifest
import android.os.Build
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.filled.Chat
import androidx.compose.material3.Badge
import androidx.compose.material3.BadgedBox
import androidx.compose.material3.Icon
import androidx.compose.material3.IconButton
import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.collectAsState
import androidx.compose.runtime.getValue
import androidx.compose.ui.platform.LocalContext
import ${SDK.android.packageName}.Clayver

/** A support icon with an unread badge that opens the Clayver chat. */
@Composable
fun ClayverSupportButton() {
    val context = LocalContext.current
    val unread by Clayver.unreadCountFlow().collectAsState(initial = 0)
    IconButton(onClick = { Clayver.openChat(context) }) {
        BadgedBox(badge = { if (unread > 0) Badge { androidx.compose.material3.Text("$unread") } }) {
            Icon(Icons.AutoMirrored.Filled.Chat, contentDescription = "Support")
        }
    }
}

/** Android 13+ needs the POST_NOTIFICATIONS runtime permission to show replies from support. */
@Composable
fun RequestClayverNotificationPermission() {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU) return
    val launcher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) { }
    LaunchedEffect(Unit) { launcher.launch(Manifest.permission.POST_NOTIFICATIONS) }
}

// Embedding the chat in your own navigation instead of a separate screen:
//   composable("support") { ClayverChatScreen() }
`;
  const dir = `${EXAMPLE_DIR}/android/${base.replace(/\./g, "/")}`;
  return [
    { path: `${dir}/ClayverSetup.kt`, content: setup, description: "configure() from Application.onCreate, Firebase Auth sign-out" },
    { path: `${dir}/ClayverMessagingService.kt`, content: messaging, description: "FirebaseMessagingService forwarding the FCM token and Clayver pushes" },
    { path: `${dir}/ClayverSupportButton.kt`, content: button, description: "Compose support button with unread badge + POST_NOTIFICATIONS request" },
  ];
}

// ------------------------------------------------------------------ Flutter

function flutterFiles(o: ExampleOptions): ExampleFile[] {
  const dart = `${HEADER("//")}
//
// Dependencies: ${SDK.flutter.package}, firebase_core, firebase_auth, firebase_messaging.
// Move this file into lib/ once the dependencies are in pubspec.yaml.
import 'package:${SDK.flutter.package}/${SDK.flutter.package}.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/material.dart';

const clayverOptions = ClayverOptions(projectId: '${o.workspace}', functionsRegion: '${o.region}');

/// Call from main() after \`await Firebase.initializeApp(...)\`.
Future<void> setupClayver() async {
  await Clayver.configure(options: clayverOptions);

  final messaging = FirebaseMessaging.instance;
  await messaging.requestPermission();
  final token = await messaging.getToken();
  if (token != null) await Clayver.setPushToken(token);
  messaging.onTokenRefresh.listen(Clayver.setPushToken);

  // Notification taps (app in background / terminated).
  FirebaseMessaging.onMessageOpenedApp.listen((message) {
    if (Clayver.isClayverNotification(message.data)) Clayver.handleNotification(message.data);
  });
  final initial = await messaging.getInitialMessage();
  if (initial != null && Clayver.isClayverNotification(initial.data)) {
    await Clayver.handleNotification(initial.data);
  }
}

/// Optional: call after your FirebaseAuth sign-in. Clayver already follows the
/// signed-in user; properties are shown to agents next to the conversation.
Future<void> clayverDidSignIn() async {
  await Clayver.setUserProperties({'plan': 'pro'});
}

/// Sign out through here: Clayver removes this device's push registrations
/// while the user is still signed in, then the user is signed out of FirebaseAuth.
Future<void> signOutWithClayver() async {
  await Clayver.logout();
  await FirebaseAuth.instance.signOut();
}

/// A support button with an unread badge that opens the Clayver chat.
class ClayverSupportButton extends StatelessWidget {
  const ClayverSupportButton({super.key});

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<int>(
      stream: Clayver.unreadCountStream,
      initialData: 0,
      builder: (context, snapshot) {
        final unread = snapshot.data ?? 0;
        return IconButton(
          tooltip: 'Support',
          onPressed: () => Clayver.openChat(),
          icon: Badge(
            isLabelVisible: unread > 0,
            label: Text('$unread'),
            child: const Icon(Icons.support_agent),
          ),
        );
      },
    );
  }
}
`;
  return [
    {
      path: `${EXAMPLE_DIR}/flutter/clayver_support.dart`,
      content: dart,
      description: "setupClayver() (configure + FCM token + notification taps), FirebaseAuth sign-out, ClayverSupportButton widget",
    },
  ];
}

export function exampleFiles(app: DetectedApp, o: ExampleOptions): ExampleFile[] {
  switch (app.platform) {
    case "ios":
      return iosFiles(o);
    case "android": {
      const pkg = app.android?.namespace ?? app.android?.applicationId ?? "com.example.app";
      return androidFiles(o, pkg);
    }
    case "flutter":
      return flutterFiles(o);
  }
}
