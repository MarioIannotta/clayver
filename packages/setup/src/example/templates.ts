import { EXAMPLE_DIR, SDK } from "../constants.js";
import type { DetectedApp } from "../detect/platform.js";

export interface ExampleOptions {
  workspace: string;
  region: string;
}

export interface ExampleFile {
  /** Relative to the app directory. */
  path: string;
  content: string;
  description: string;
}

const HEADER = (comment: string) =>
  [
    `${comment} Generated by \`npx clayver init\`. Sample code: copy it into your app and adapt it.`,
    `${comment} It contains no secrets. Clayver follows your app's Firebase Auth user: sign users in with`,
    `${comment} Firebase Auth as usual (the customer id is the Firebase uid). No extra backend is needed.`,
  ].join("\n");

// ------------------------------------------------------------------ iOS

function iosFiles(o: ExampleOptions): ExampleFile[] {
  const setup = `${HEADER("//")}
import SwiftUI
import UIKit
import UserNotifications
import FirebaseCore
import FirebaseMessaging
import FirebaseAuth
import ${SDK.ios.module}

/// Clayver bootstrap for a SwiftUI app.
///
///     @main
///     struct MyApp: App {
///         @UIApplicationDelegateAdaptor(ClayverAppDelegate.self) var appDelegate
///         var body: some Scene { WindowGroup { ContentView() } }
///     }
enum ClayverSetup {
    static let options = ClayverOptions(projectId: "${o.workspace}", functionsRegion: "${o.region}")

    /// Call once at launch, after FirebaseApp.configure().
    static func configure() async {
        do {
            try await Clayver.configure(options)
        } catch {
            print("Clayver.configure failed: \\(error)")
        }
    }

    /// Optional: call after your Firebase Auth sign-in. Clayver already follows the signed-in
    /// user; properties are shown to agents next to the conversation.
    static func didSignIn() async {
        try? await Clayver.setUserProperties(["plan": .string("pro")])
    }

    /// Sign out through here: Clayver removes this device's push registrations while the
    /// user is still signed in, then the user is signed out of Firebase Auth.
    static func signOut() async throws {
        try await Clayver.logout()
        try Auth.auth().signOut()
    }
}

/// Push notifications: forwards the FCM token to Clayver and opens the chat
/// when a Clayver notification is tapped. Requires the Push Notifications and
/// Background Modes > Remote notifications capabilities, and an APNs key
/// uploaded in Firebase console > Project settings > Cloud Messaging.
final class ClayverAppDelegate: NSObject, UIApplicationDelegate, UNUserNotificationCenterDelegate, MessagingDelegate {
    func application(
        _ application: UIApplication,
        didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
    ) -> Bool {
        FirebaseApp.configure()
        UNUserNotificationCenter.current().delegate = self
        Messaging.messaging().delegate = self
        Task { await ClayverSetup.configure() }
        UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .badge, .sound]) { granted, _ in
            guard granted else { return }
            DispatchQueue.main.async { application.registerForRemoteNotifications() }
        }
        return true
    }

    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        Messaging.messaging().apnsToken = deviceToken
    }

    func messaging(_ messaging: Messaging, didReceiveRegistrationToken fcmToken: String?) {
        guard let fcmToken else { return }
        Task { try? await Clayver.setFCMToken(fcmToken) }
    }

    func userNotificationCenter(
        _ center: UNUserNotificationCenter,
        willPresent notification: UNNotification
    ) async -> UNNotificationPresentationOptions {
        Clayver.isClayverNotification(userInfo: notification.request.content.userInfo) ? [.banner, .sound, .badge] : []
    }

    @MainActor
    func userNotificationCenter(_ center: UNUserNotificationCenter, didReceive response: UNNotificationResponse) async {
        _ = Clayver.handleNotification(userInfo: response.notification.request.content.userInfo)
    }
}
`;
  const button = `${HEADER("//")}
import SwiftUI
import ${SDK.ios.module}

/// A "Support" button with an unread badge that opens the Clayver chat.
///
///     .toolbar { ClayverSupportButton() }
struct ClayverSupportButton: View {
    @State private var isChatPresented = false
    @State private var unreadCount = 0

    var body: some View {
        Button {
            isChatPresented = true
        } label: {
            Label("Support", systemImage: "bubble.left.and.bubble.right")
                .overlay(alignment: .topTrailing) {
                    if unreadCount > 0 {
                        Text("\\(unreadCount)")
                            .font(.caption2.bold())
                            .foregroundStyle(.white)
                            .padding(4)
                            .background(Circle().fill(.red))
                            .offset(x: 10, y: -10)
                            .accessibilityLabel("\\(unreadCount) unread support messages")
                    }
                }
        }
        .sheet(isPresented: $isChatPresented) {
            ClayverChatView()
        }
        .task {
            do {
                for try await count in Clayver.unreadCountUpdates() {
                    unreadCount = count
                }
            } catch {
                unreadCount = 0
            }
        }
    }
}

// UIKit alternative:
//   Clayver.openChat(from: self)
`;
  return [
    { path: `${EXAMPLE_DIR}/ios/ClayverSetup.swift`, content: setup, description: "configure(), Firebase Auth sign-out and the push AppDelegate (FCM token + notification taps)" },
    { path: `${EXAMPLE_DIR}/ios/ClayverSupportButton.swift`, content: button, description: "SwiftUI support button with unread badge that presents ClayverChatView" },
  ];
}

