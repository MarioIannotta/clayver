import { join } from "node:path";
import { CLI_VERSION } from "../constants.js";
import type { Assets } from "../core/assets.js";
import type { FileChange } from "../core/files.js";

export interface FunctionsParams {
  projectId: string;
  bootstrapAdmins: string[];
  region: string;
  dashboardUrl?: string;
  /** Reject callable requests without a valid App Check token. */
  enforceAppCheck?: boolean;
  /** Parameters the developer added themselves; written back unchanged. */
  extra?: Record<string, string>;
}

/** Entry the generated folder loads. The implementation stays inside the installed `clayver` package. */
export const FUNCTIONS_ENTRY = [
  "// Cloud Functions shipped inside the `clayver` package.",
  "// `npx clayver update` bumps that dependency; this file only re-exports it.",
  'module.exports = require("clayver/functions");',
  "",
].join("\n");

interface BundledFunctionsPackage {
  engines?: { node?: string };
  dependencies?: Record<string, string>;
}

/**
 * package.json for `clayver-functions/`. Same idea as `clayver-dashboard/`:
 * the app folder depends on `clayver` instead of carrying a copy of the source.
 * firebase-admin and firebase-functions stay direct dependencies so Cloud
 * Functions installs them next to this folder and the code inside `clayver` can resolve them.
 */
export function functionsPackageJson(assets: Assets): string {
  const bundled = JSON.parse(assets.functionsFiles.get("package.json")?.toString("utf8") ?? "{}") as BundledFunctionsPackage;
  return `${JSON.stringify(
    {
      name: "clayver-functions",
      private: true,
      version: "0.0.0",
      description: "Clayver Cloud Functions for this app. Generated by `npx clayver init`. The implementation ships in the `clayver` package.",
      main: "index.js",
      engines: bundled.engines ?? { node: "22" },
      dependencies: {
        clayver: `^${CLI_VERSION}`,
        ...(bundled.dependencies ?? {}),
      },
    },
    null,
    2,
  )}\n`;
}

/** The functions folder Clayver writes into the developer's Firebase directory. */
export function functionsFileChanges(assets: Assets, functionsDir: string): FileChange[] {
  return [
    {
      path: join(functionsDir, "package.json"),
      content: functionsPackageJson(assets),
      kind: "functions",
      description: "Depends on the clayver package, which contains the Cloud Functions",
    },
    {
      path: join(functionsDir, "index.js"),
      content: FUNCTIONS_ENTRY,
      kind: "functions",
      description: "Re-exports the Cloud Functions from the clayver package",
    },
    {
      path: join(functionsDir, ".gitignore"),
      content: "node_modules/\n*.local\nfirebase-debug.log\n",
      kind: "functions",
      description: "Keeps installed dependencies out of git",
      showDiff: false,
    },
  ];
}

export const EMAIL_PATTERN = /^[^\s@,]+@[^\s@,]+\.[^\s@,]+$/;

export function parseEmails(value: string): string[] {
  return value
    .split(/[,\s]+/)
    .map((e) => e.trim().toLowerCase())
    .filter(Boolean);
}

export function validateEmails(value: string): true | string {
  const emails = parseEmails(value);
  if (!emails.length) return "Enter at least one email address.";
  const bad = emails.find((e) => !EMAIL_PATTERN.test(e));
  return bad ? `"${bad}" is not an email address.` : true;
}

/**
 * `.env.<projectId>` next to the functions source. The Firebase CLI loads it at
 * deploy time to fill the functions' params. Nothing in it is secret.
 */
export function functionsEnvFile(p: FunctionsParams): string {
  return [
    `# Parameters for the Clayver Cloud Functions in Firebase project "${p.projectId}".`,
    "# Generated by `npx clayver init`. Edit, then redeploy with `npx clayver update`.",
    "# Nothing here is secret. Customers and agents are identified by Firebase Authentication.",
    "",
    "# Emails allowed to claim the first admin seat of a workspace (clayverBootstrapAdmin).",
    `CLAYVER_BOOTSTRAP_ADMINS=${p.bootstrapAdmins.join(",")}`,
    "# Region every Clayver function is deployed to. Must match `functionsRegion` in the SDK options.",
    `CLAYVER_FUNCTIONS_REGION=${p.region}`,
    "# Public URL of the Clayver dashboard, used for web push click-through links (optional).",
    `CLAYVER_DASHBOARD_URL=${p.dashboardUrl ?? ""}`,
    "# Reject callable requests without a valid App Check token. Turn on once every app ships App Check.",
    `CLAYVER_ENFORCE_APP_CHECK=${p.enforceAppCheck ? "true" : "false"}`,
    ...extraLines(p.extra),
    "",
  ].join("\n");
}

/** Keys functionsEnvFile writes itself; anything else in an existing file is kept as the developer's own. */
export const CLAYVER_ENV_KEYS = [
  "CLAYVER_BOOTSTRAP_ADMINS",
  "CLAYVER_FUNCTIONS_REGION",
  "CLAYVER_DASHBOARD_URL",
  "CLAYVER_ENFORCE_APP_CHECK",
];

/** Keys earlier versions wrote that no function reads any more; dropped instead of kept as the developer's own. */
const RETIRED_ENV_KEYS = ["CLAYVER_ALLOW_UNVERIFIED_IDENTITY"];

function extraLines(extra: Record<string, string> | undefined): string[] {
  const entries = Object.entries(extra ?? {}).filter(([k]) => !CLAYVER_ENV_KEYS.includes(k) && !RETIRED_ENV_KEYS.includes(k));
  return entries.length ? ["", "# Your own parameters (kept by `npx clayver update`).", ...entries.map(([k, v]) => `${k}=${v}`)] : [];
}

/** Reads values back from an existing env file so re-running init keeps them. */
export function parseEnvFile(text: string | undefined): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of (text ?? "").split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (m) out[m[1] as string] = (m[2] as string).replace(/^["']|["']$/g, "");
  }
  return out;
}
