/** The hosting block `clayver dashboard deploy` uses. */
export function dashboardHosting(site?: string): Record<string, unknown> {
  return {
    ...(site ? { site } : {}),
    public: DASHBOARD_PUBLIC_DIR,
    ignore: ["firebase.json", "**/.*", "**/node_modules/**"],
    rewrites: [{ source: "**", destination: "/index.html" }],
    headers: [
      { source: "/assets/**", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
      { source: "/firebase-messaging-sw.js", headers: [{ key: "Cache-Control", value: "no-cache" }] },
      { source: "/index.html", headers: [{ key: "Cache-Control", value: "no-cache" }] },
      { source: `/${DASHBOARD_CONFIG_FILE}`, headers: [{ key: "Cache-Control", value: "no-cache" }] },
      {
        source: "**",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
        ],
      },
    ],
  };
}

export interface DashboardFirebaseJsonPlan {
  content: string;
  /** The existing hosting entry serves something else; replacing it needs a human. */
  conflict: boolean;
  site?: string;
}

/**
 * The dashboard folder's firebase.json: adds the hosting entry, or keeps an
 * existing one that already serves `public/` (setting `site` when asked).
 */
export function planDashboardFirebaseJson(existingText: string | undefined, site?: string): DashboardFirebaseJsonPlan {
  const text = existingText && existingText.trim() ? existingText : "{}\n";
  const json = parseJsonc<Record<string, unknown>>(text, "firebase.json") ?? {};
  const hosting = json.hosting;
  if (hosting === undefined) {
    const content = existingText && existingText.trim() ? setProperty(text, [], "hosting", dashboardHosting(site)) : `${JSON.stringify({ hosting: dashboardHosting(site) }, null, 2)}\n`;
    return { content, conflict: false, site };
  }
  if (isObject(hosting) && hosting.public === DASHBOARD_PUBLIC_DIR) {
    const currentSite = typeof hosting.site === "string" ? hosting.site : undefined;
    if (site && currentSite !== site) return { content: setProperty(text, ["hosting"], "site", site), conflict: false, site };
    return { content: text, conflict: false, site: currentSite };
  }
  return { content: replaceValue(text, ["hosting"], dashboardHosting(site)), conflict: true, site };
}
