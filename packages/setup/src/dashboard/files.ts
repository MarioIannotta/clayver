import { CLI_VERSION, DASHBOARD_CONFIG_FILE, DASHBOARD_PUBLIC_DIR } from "../constants.js";
import { parseJsonc, replaceValue, setProperty } from "../core/jsonedit.js";

/** Firebase web config keys the dashboard uses; all of them are public identifiers. */
export const WEB_CONFIG_KEYS = [
  "apiKey",
  "authDomain",
  "databaseURL",
  "projectId",
  "storageBucket",
  "messagingSenderId",
  "appId",
  "measurementId",
] as const;

export type WebConfig = Partial<Record<(typeof WEB_CONFIG_KEYS)[number], string>>;

/** The dashboard's runtime config (`clayver.config.json`). Same shape as `DashboardConfigFile` in @clayver/core. */
export interface DashboardConfigJson {
  firebase: WebConfig;
  projectId: string;
  functionsRegion: string;
  vapidKey?: string;
  useEmulators?: boolean;
  emulatorHost?: string;
  [extra: string]: unknown;
}

function isObject(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === "object" && !Array.isArray(v);
}

export function pickWebConfig(value: unknown): WebConfig {
  const out: WebConfig = {};
  if (!isObject(value)) return out;
  for (const k of WEB_CONFIG_KEYS) {
    const v = value[k];
    if (typeof v === "string" && v) out[k] = v;
  }
  return out;
}

/**
 * Reads the web config from `firebase apps:sdkconfig WEB <appId> --json`.
 * Depending on the Firebase CLI version, `result` is the config itself,
 * `{ sdkConfig }`, or `{ fileName, fileContents }` with a JS snippet.
 */
export function parseWebSdkConfig(result: unknown): WebConfig | undefined {
  if (!isObject(result)) return undefined;
  if (isObject(result.sdkConfig)) return pickWebConfig(result.sdkConfig);
  if (typeof result.apiKey === "string") return pickWebConfig(result);
  if (typeof result.fileContents === "string") {
    const out: WebConfig = {};
    for (const k of WEB_CONFIG_KEYS) {
      const m = new RegExp(`["']?${k}["']?\\s*:\\s*["']([^"']*)["']`).exec(result.fileContents);
      if (m?.[1]) out[k] = m[1];
    }
    return Object.keys(out).length ? out : undefined;
  }
  return undefined;
}

/**
 * clayver.config.json: the generated keys first, then anything the developer
 * added (for example `vapidKey`), which is kept as is.
 */
export function dashboardConfigJson(
  existingText: string | undefined,
  input: { firebase: WebConfig; workspace: string; region: string },
): string {
  let existing: Record<string, unknown> = {};
  if (existingText) {
    try {
      const parsed = JSON.parse(existingText) as unknown;
      if (isObject(parsed)) existing = parsed;
    } catch {
      // Unparseable: replaced (the file writer shows the diff and asks first).
    }
  }
  const { firebase: _f, projectId: _p, functionsRegion: _r, ...extra } = existing;
  const prevFirebase = isObject(existing.firebase) ? existing.firebase : {};
  const firebase: Record<string, unknown> = { ...input.firebase };
  // Keep fields the developer added to the firebase block that Firebase did not return.
  for (const [k, v] of Object.entries(prevFirebase)) if (!(k in firebase)) firebase[k] = v;
  const out: DashboardConfigJson = { firebase: firebase as WebConfig, projectId: input.workspace, functionsRegion: input.region, ...extra };
  if (!("vapidKey" in out)) out.vapidKey = "";
  return `${JSON.stringify(out, null, 2)}\n`;
}

